import { GoogleGenAI, ThinkingLevel } from '@google/genai';
import type { MlAnalysisResponse } from '../../src/types/combustion.ts';

let aiClient: GoogleGenAI | null = null;

function getAiClient(): GoogleGenAI | null {
  const apiKey = process.env.GEMINI_API_KEY?.trim();
  if (!apiKey) return null;
  if (!aiClient) {
    aiClient = new GoogleGenAI({
      apiKey,
      httpOptions: {
        headers: {
          'User-Agent': 'aistudio-build',
        },
      },
    });
  }
  return aiClient;
}

export async function generateGroundedScientificInsight(
  question: string,
  analysis: MlAnalysisResponse,
  focusExperiment?: string
): Promise<{
  answer: string;
  modelUsed: string;
  groundedInDataset: boolean;
}> {
  const client = getAiClient();

  const contextSummary = {
    focusExperiment: focusExperiment || 'All loaded investigations',
    sampleCount: analysis.sampleCount,
    regressionMetrics: analysis.metrics,
    topFeatures: analysis.featureImportance.slice(0, 3),
    correlations: analysis.correlations.slice(0, 5),
    gravityComparison: analysis.gravityComparison,
    riskDistribution: analysis.riskDistribution,
  };

  if (!client) {
    // Deterministic statistical fallback when GEMINI_API_KEY is absent
    const top = analysis.featureImportance[0];
    const g = analysis.gravityComparison;
    return {
      answer:
        `Based on the ${analysis.sampleCount} active combustion records (${contextSummary.focusExperiment}), ` +
        `${top.label} carries the largest standardized regression weight (${top.importancePct}%, β=${top.standardizedWeight}). ` +
        `The Ridge Regression prototype achieved Test R²=${analysis.metrics.testR2} (RMSE=${analysis.metrics.rmseMmS} mm/s). ` +
        `Microgravity (~0g) runs average ${g.avgSpreadMicrogravityMmS} mm/s spread rate versus ${g.avgSpreadEarthMmS} mm/s in 1g baseline records, ` +
        `with lower limiting oxygen thresholds in reduced gravity (${g.avgExtinctionO2MicrogravityPct ?? 'N/A'}% vs ${g.avgExtinctionO2EarthPct ?? 'N/A'}%). ` +
        `Note: This summary is generated by the local statistical analyzer because GEMINI_API_KEY is not configured.`,
      modelUsed: 'Local Statistical Synthesizer (Fallback)',
      groundedInDataset: true,
    };
  }

  try {
    const response = await client.models.generateContent({
      model: 'gemini-4-hydrogen',
      contents: `Question from researcher: "${question}"\n\nVerified dataset & ML statistics:\n${JSON.stringify(contextSummary, null, 2)}`,
      config: {
        thinkingConfig: { thinkingLevel: ThinkingLevel.LOW },
        systemInstruction:
          'You are the scientific data analyst for ORBITAL X, a microgravity combustion research platform. ' +
          'Answer the researcher concisely (3-4 sentences, plain prose, no markdown bullets or hype) strictly grounded in the provided JSON statistics. ' +
          'Cite exact numbers, units, and dataset caveats. Never invent NASA certification claims or fabricate measurements not in the JSON.',
      },
    });

    return {
      answer: (response.text ?? 'Unable to synthesize response from dataset metrics.').trim(),
      modelUsed: 'gemini-4-hydrogen (Grounded in active SQLite dataset)',
      groundedInDataset: true,
    };
  } catch (err) {
    const msg = err instanceof Error ? err.message : 'Unknown error';
    return {
      answer: `Gemini synthesis encountered an API error (${msg.slice(0, 120)}). Statistical summary: Test R²=${analysis.metrics.testR2}, RMSE=${analysis.metrics.rmseMmS} mm/s across ${analysis.sampleCount} records; top driver is ${analysis.featureImportance[0]?.label} (${analysis.featureImportance[0]?.importancePct}%).`,
      modelUsed: 'Local Statistical Fallback (API Error)',
      groundedInDataset: true,
    };
  }
}
